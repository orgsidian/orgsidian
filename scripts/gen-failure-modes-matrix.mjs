/**
 * Parse `tests/failure_modes.rs` for `#[ignore = "implemented in Epic N"]`
 * blocks, capture the owning epic + the adjacent `fn <name>()` token. Returns
 * an array in top-down source order.
 */
function scanHarness(src) {
  const lines = src.split("\n");
  const rows = [];
  const ignoreRe = /^\s*#\[ignore\s*=\s*"implemented in Epic (\d+)"\]\s*$/;
  const fnRe = /^\s*fn\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(/;

  for (let i = 0; i < lines.length; i++) {
    const ignoreMatch = lines[i].match(ignoreRe);
    if (!ignoreMatch) continue;
    const epic = Number(ignoreMatch[1]);
    for (let j = i + 1; j < lines.length; j++) {
      const fnMatch = lines[j].match(fnRe);
      if (!fnMatch) {
        if (lines[j].trim() === "") continue;
        break;
      }
      rows.push({ category: fnMatch[1], epic });
      break;
    }
  }
  return rows;
}

function render(rows) {
  const lines = [];
  lines.push("<!-- regenerated by: pnpm gen:failure-modes-matrix -->");
  lines.push("<!-- Source of truth: tests/failure_modes.rs (LD-41 catalog). -->");
  lines.push("");
  lines.push("# LD-41 Failure-mode Coverage Matrix");
  lines.push("");
  lines.push(
    "Auto-generated from `tests/failure_modes.rs`. Regenerate via `pnpm gen:failure-modes-matrix` after any change to the harness.",
  );
  lines.push("");
  lines.push(
    "Status `#[ignore] (implemented in Epic N)` means the placeholder is still red-phase. Downstream stories in the owning epic replace the `#[ignore]` + the `unimplemented!` body with the real fault-injection assertion.",
  );
  lines.push("");
  lines.push("| Category | Owning Epic | Mechanism | Status |");
  lines.push("|---|---|---|---|");

  for (const row of rows) {
    const meta = CATEGORY_META[row.category];
    const label = meta ? meta.label : row.category;
    const mechanism = meta ? meta.mechanism : "_(mechanism TBD — update gen-failure-modes-matrix.mjs)_";
    const status = `#[ignore] (implemented in Epic ${row.epic})`;
    lines.push(`| ${label} | Epic ${row.epic} | ${mechanism} | ${status} |`);
  }

  lines.push("");
  lines.push(
    "_Mechanism column sources: test-design.md §6.7 LD-41 Coverage Matrix (rows 1-9) + architecture.md L1209 (row 10, LD-57 Refile cross-file atomicity)._",
  );
  lines.push("");

  return lines.join("\n");
}

const src = readFileSync(harnessPath, "utf8");
const rows = scanHarness(src);
process.stdout.write(render(rows));
